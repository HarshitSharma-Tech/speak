import json
import uuid
from concurrent.futures import ThreadPoolExecutor
from typing import List, Optional
from fastapi import APIRouter, Depends, HTTPException, status
from sqlalchemy.orm import Session
from app.db.session import get_db
from app.models.document import Document, DocumentChunk
from app.models.course import Course, Module, CheatSheet
from app.schemas.course import CourseResponse, CourseCreateRequest, ModuleResponse, CheatSheetResponse, SourceReferenceResponse
from app.services.course_service import CourseService

router = APIRouter(prefix="/courses", tags=["Courses"])


@router.post("/generate", response_model=CourseResponse, status_code=status.HTTP_201_CREATED)
def generate_course_from_document(
    request: CourseCreateRequest,
    db: Session = Depends(get_db)
):
    """
    Generate a complete course curriculum and high-yield cheat sheet
    derived strictly from an uploaded textbook document (executed concurrently for speed).
    """
    document = db.query(Document).filter(Document.id == request.document_id).first()
    if not document:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Textbook document not found.")

    chunks = db.query(DocumentChunk).filter(DocumentChunk.document_id == document.id).order_by(DocumentChunk.chunk_index).all()
    if not chunks:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Document has no processed text chunks to generate a course from."
        )

    chunk_dicts = [
        {"id": c.id, "chunk_index": c.chunk_index, "page_number": c.page_number, "content": c.content}
        for c in chunks
    ]

    title_hint = request.title or document.original_name

    # Execute course outline and cheat sheet generation concurrently to halve latency
    with ThreadPoolExecutor(max_workers=2) as executor:
        outline_future = executor.submit(
            CourseService.generate_course_outline,
            title_hint,
            chunk_dicts,
            request.target_modules
        )
        cheat_future = executor.submit(
            CourseService.generate_cheat_sheet,
            title_hint,
            chunk_dicts
        )
        outline_data = outline_future.result()
        cheat_sheet_data = cheat_future.result()

    # Create Course
    course_id = str(uuid.uuid4())
    course = Course(
        id=course_id,
        document_id=document.id,
        title=outline_data.get("course_title", title_hint),
        description=outline_data.get("course_description", "Course generated by LearnSync AI"),
        status="ready"
    )
    db.add(course)
    db.flush()

    # Create Modules
    module_objs = []
    for m in outline_data.get("modules", []):
        mod_id = str(uuid.uuid4())
        mod = Module(
            id=mod_id,
            course_id=course_id,
            module_order=m.get("module_order", 1),
            title=m.get("title", f"Module {m.get('module_order', 1)}"),
            summary=m.get("summary", ""),
            key_topics_json=json.dumps(m.get("key_topics", [])),
            learning_content=m.get("learning_content", ""),
            source_chunk_ids_json=json.dumps(m.get("source_chunk_ids", []))
        )
        module_objs.append(mod)

    db.add_all(module_objs)

    cheat_sheet = CheatSheet(
        id=str(uuid.uuid4()),
        course_id=course_id,
        title=cheat_sheet_data.get("title", f"{course.title} Cheat Sheet"),
        summary=cheat_sheet_data.get("summary", ""),
        key_definitions_json=json.dumps(cheat_sheet_data.get("key_definitions", [])),
        important_formulas_json=json.dumps(cheat_sheet_data.get("important_formulas", [])),
        high_yield_revision_points_json=json.dumps(cheat_sheet_data.get("high_yield_revision_points", [])),
        source_chunk_ids_json=json.dumps(cheat_sheet_data.get("source_chunk_ids", []))
    )
    db.add(cheat_sheet)

    db.commit()
    db.refresh(course)

    return _format_course_response(course)


@router.get("", response_model=List[CourseResponse])
def list_courses(db: Session = Depends(get_db)):
    """List all generated courses."""
    courses = db.query(Course).order_by(Course.created_at.desc()).all()
    return [_format_course_response(c) for c in courses]


@router.get("/{course_id}", response_model=CourseResponse)
def get_course(course_id: str, db: Session = Depends(get_db)):
    """Get full details of a course."""
    course = db.query(Course).filter(Course.id == course_id).first()
    if not course:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Course not found.")
    return _format_course_response(course)


@router.get("/{course_id}/modules/{module_id}", response_model=ModuleResponse)
def get_module(course_id: str, module_id: str, db: Session = Depends(get_db)):
    """Get detailed learning page for a specific module."""
    mod = db.query(Module).filter(Module.id == module_id, Module.course_id == course_id).first()
    if not mod:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Module not found.")
    return _format_module_response(mod)


@router.get("/{course_id}/cheat-sheet", response_model=CheatSheetResponse)
def get_cheat_sheet(course_id: str, db: Session = Depends(get_db)):
    """Get cheat sheet for a course."""
    cs = db.query(CheatSheet).filter(CheatSheet.course_id == course_id).first()
    if not cs:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Cheat sheet not found.")
    return _format_cheat_sheet_response(cs)


@router.get("/{course_id}/sources/{chunk_id}", response_model=SourceReferenceResponse)
def get_source_reference(course_id: str, chunk_id: str, db: Session = Depends(get_db)):
    """Look up the exact grounded textbook page and verbatim excerpt for any artifact."""
    chunk = db.query(DocumentChunk).filter(DocumentChunk.id == chunk_id).first()
    if not chunk:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Source chunk reference not found.")

    doc = db.query(Document).filter(Document.id == chunk.document_id).first()
    return SourceReferenceResponse(
        chunk_id=chunk.id,
        document_id=chunk.document_id,
        document_name=doc.original_name if doc else "Textbook",
        page_number=chunk.page_number,
        content_snippet=chunk.content
    )


@router.delete("/{course_id}", status_code=status.HTTP_200_OK)
def delete_course(course_id: str, db: Session = Depends(get_db)):
    """Cascade delete course and all modules, quizzes, and cheat sheets."""
    course = db.query(Course).filter(Course.id == course_id).first()
    if not course:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Course not found.")
    db.delete(course)
    db.commit()
    return {"message": "Course deleted successfully.", "id": course_id}


# Helper formatting functions
def _format_module_response(m: Module) -> ModuleResponse:
    return ModuleResponse(
        id=m.id,
        course_id=m.course_id,
        module_order=m.module_order,
        title=m.title,
        summary=m.summary,
        key_topics=json.loads(m.key_topics_json) if m.key_topics_json else [],
        learning_content=m.learning_content,
        source_chunk_ids=json.loads(m.source_chunk_ids_json) if m.source_chunk_ids_json else [],
        created_at=m.created_at
    )


def _format_cheat_sheet_response(cs: CheatSheet) -> CheatSheetResponse:
    return CheatSheetResponse(
        id=cs.id,
        course_id=cs.course_id,
        title=cs.title,
        summary=cs.summary,
        key_definitions=json.loads(cs.key_definitions_json) if cs.key_definitions_json else [],
        important_formulas=json.loads(cs.important_formulas_json) if cs.important_formulas_json else [],
        high_yield_revision_points=json.loads(cs.high_yield_revision_points_json) if cs.high_yield_revision_points_json else [],
        source_chunk_ids=json.loads(cs.source_chunk_ids_json) if cs.source_chunk_ids_json else [],
        created_at=cs.created_at
    )


def _format_course_response(course: Course) -> CourseResponse:
    return CourseResponse(
        id=course.id,
        document_id=course.document_id,
        title=course.title,
        description=course.description,
        status=course.status,
        created_at=course.created_at,
        modules=[_format_module_response(m) for m in course.modules],
        cheat_sheets=[_format_cheat_sheet_response(cs) for cs in course.cheat_sheets]
    )
